// Runs on the existing staging origin using fixture-only Finance API interception.
// No source registration, shared runtime change or financial database writes.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../..');
const require = createRequire(import.meta.url);
const esbuild = require(path.join(root, 'app-shell/web/node_modules/esbuild'));
const { chromium } = await import(process.env.FINANCE_PLAYWRIGHT_MODULE ? pathToFileURL(process.env.FINANCE_PLAYWRIGHT_MODULE).href : 'playwright');
const fixtures = JSON.parse(fs.readFileSync(process.env.FINANCE_UI_FIXTURES, 'utf8'));
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'finance-ui-check-'));
fs.writeFileSync(path.join(tmp, 'entry.jsx'), `import React from 'react';import {createRoot} from 'react-dom/client';import FinancePage from ${JSON.stringify(path.join(root, 'features/finance/web/FinancePage.jsx'))};function FixtureShell(){const [workspace,setWorkspace]=React.useState('Overview');React.useEffect(()=>{window.financeFixtureNavigate=setWorkspace;},[]);return <FinancePage initialWorkspace={workspace} onWorkspaceChange={setWorkspace}/>;}createRoot(document.getElementById('finance-fixture')).render(<FixtureShell/>);`);
esbuild.buildSync({ entryPoints: [path.join(tmp, 'entry.jsx')], outfile: path.join(tmp, 'bundle.js'), bundle: true, format: 'iife', nodePaths: [path.join(root, 'app-shell/web/node_modules')], define: { 'process.env.NODE_ENV': '"development"' } });
const browser = await chromium.launch({ headless: true });
const failures = [], checks = [], requests = [];
let readOnly = false, page;
try {
  page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', (error) => failures.push(error.message));
  await page.clock.install({ time: new Date('2026-01-31T10:00:00Z') });
  await page.route('**/api/finance/**', async (route) => {
    const request = route.request(), url = new URL(request.url()), resource = url.pathname.replace('/api/finance/', '');
    requests.push({ path: url.pathname, method: request.method(), body: request.postData() });
    let key = resource;
    if (resource === 'reports/monthly-series') key = `series/${url.searchParams.get('kind')}`;
    if (resource === 'reports/comparison') key = `comparison/${url.searchParams.get('kind')}`;
    let data = fixtures[key];
    if (resource === 'meta' && readOnly) data = { ...data, permissionsGranted: ['finance.view', 'finance.reports.subscribers.view'] };
    if (resource.endsWith('/csv')) { await route.fulfill({ status: 200, contentType: 'text/csv', headers: { 'Content-Disposition': 'attachment; filename="finance.csv"' }, body: 'Report,amount\nFixture,100.00\n' }); return; }
    if (request.method() !== 'GET') { await route.fulfill({ status: 403, contentType: 'application/json', body: JSON.stringify({ detail: 'Fixture-only browser verification; posting is rejected.' }) }); return; }
    await route.fulfill({ status: data === undefined ? 404 : 200, contentType: 'application/json', body: JSON.stringify(data === undefined ? { detail: `Missing fixture ${key}` } : data) });
  });
  async function mount() {
    await page.goto(process.env.FINANCE_STAGING_ORIGIN || 'http://127.0.0.1:8280/');
    await page.evaluate(() => { document.body.innerHTML = '<main class="page-body" id="finance-fixture"></main>'; localStorage.setItem('threejmain_token', 'fixture-only'); });
    await page.addStyleTag({ path: path.join(tmp, 'bundle.css') });
    await page.addScriptTag({ path: path.join(tmp, 'bundle.js') });
    await page.locator('.finance-header').getByRole('heading', { name: 'Overview', exact: true }).waitFor();
    await page.getByText('Loading reports and their supporting records…').waitFor({ state: 'hidden' });
  }
  async function workspace(name) { await page.evaluate((next) => window.financeFixtureNavigate(next), name); await page.locator('.finance-header').getByRole('heading', { name, exact: true }).waitFor(); await page.getByText('Loading reports and their supporting records…').waitFor({ state: 'hidden' }); }
  async function close() { await page.getByRole('dialog').getByRole('button', { name: 'Close records', exact: true }).click(); }
  await mount();
  assert.equal(await page.getByRole('navigation', { name: 'Finance workspaces' }).count(), 0);
  await page.getByRole('button', { name: /Available controlled cash/ }).click();
  await page.getByRole('dialog').getByText('Closing balance', { exact: true }).waitFor();
  await close(); checks.push('overview summary opens controlled account records');
  await workspace('Accounts & Transfers');
  await page.getByLabel('Search records').fill('Petty cash office');
  await page.getByText('1–25 of 26 records').waitFor();
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await page.getByText('26–26 of 26 records').waitFor();
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click();
  await page.getByRole('button', { name: 'New account', exact: true }).click();
  await page.getByRole('dialog').getByLabel('Account name').fill('Review account draft');
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click();
  checks.push('account search, pagination, create form and dialog focus return');
  await workspace('Financial Reports');
  await page.getByRole('button', { name: /Net profit Unavailable/ }).click();
  await page.getByRole('dialog').getByText(/Incomplete recognition or costing/).waitFor();
  await close();
  const expensePoint = page.locator('g[role="button"]').filter({ has: page.locator('title', { hasText: 'Recorded expenses' }) }).last();
  await expensePoint.focus(); await page.keyboard.press('Enter');
  await page.getByRole('dialog').getByRole('heading', { name: 'Recorded expenses, including direct costs' }).waitFor();
  await close(); checks.push('unavailable profit stays labeled and chart keyboard drill-down opens expense journal lines');
  await page.getByRole('button', { name: 'Cash flow & balances', exact: true }).click();
  await page.getByText('Loading reports and their supporting records…').waitFor({ state: 'hidden' });
  const wallet = page.locator('.finance-bar').filter({ hasText: 'COMPANY_GCASH' }).last();
  await wallet.click();
  await page.getByRole('dialog').getByText('Internal', { exact: true }).waitFor();
  await close(); checks.push('cash chart retains internal account movement without treating it as income');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV', exact: true }).click();
  assert.match((await download).suggestedFilename(), /finance-cash-flow/);
  await page.getByRole('button', { name: 'Printable report', exact: true }).click();
  await page.getByRole('dialog').getByRole('heading', { name: /Finance Management — Cash flow/ }).waitFor();
  await page.emulateMedia({ media: 'print' });
  await page.evaluate(() => document.body.classList.add('finance-printing'));
  assert.equal(await page.locator('.finance-print-region').evaluate((el) => getComputedStyle(el).visibility), 'visible');
  assert.equal(await page.locator('.finance-header').evaluate((el) => getComputedStyle(el).visibility), 'hidden');
  await page.evaluate(() => document.body.classList.remove('finance-printing'));
  await page.emulateMedia({ media: 'screen' });
  await page.getByRole('dialog').getByRole('button', { name: 'Close preview', exact: true }).click();
  checks.push('authenticated CSV download and full-period print layout');
  await workspace('Expenses & Payables');
  await page.getByText('Loading expense records…').waitFor({ state: 'hidden' });
  const submitted = page.locator('tbody tr').filter({ hasText: 'Needs approval' });
  await submitted.getByRole('button').first().click();
  await page.getByRole('heading', { name: /Expense #/ }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Approve', exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Reject', exact: true }).count(), 0);
  checks.push('creator cannot review their submitted expense in the interface');
  await page.getByRole('button', { name: 'Close detail', exact: true }).click();
  await page.locator('tbody tr').filter({ hasText: 'Partially paid' }).getByRole('button').first().click();
  await page.getByRole('button', { name: 'Record payment', exact: true }).click();
  await page.getByRole('dialog').getByLabel('Actual funding account').selectOption(fixtures.accounts.find((r) => r.kind === 'CASH').id);
  await page.getByRole('dialog').getByLabel('Amount paid (PHP)').fill('25.00');
  await page.getByRole('dialog').getByLabel('Payment purpose / evidence').fill('Reviewed partial supplier payment');
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm and save', exact: true }).click();
  await page.getByText('Fixture-only browser verification; posting is rejected.', { exact: true }).first().waitFor();
  const attempt = requests.find((r) => r.method === 'POST');
  assert.match(attempt.path, /\/payables\/[^/]+\/payments$/);
  assert.equal(JSON.parse(attempt.body).amount, '25.00');
  assert.equal(JSON.parse(attempt.body).accountId, fixtures.accounts.find((r) => r.kind === 'CASH').id);
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(await page.getByText(/A Finance request is awaiting confirmation/).count(), 0);
  checks.push('partial payment selects the named account and preserves decimal amount; definitive rejection clears saved retry');

  await workspace('Income & Collections');
  await page.getByText('Loading income and source evidence…').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Other income & funding', exact: true }).click();
  await page.getByRole('button', { name: 'New other income / funding', exact: true }).click();
  await page.getByRole('dialog').getByLabel('Inflow classification').selectOption('LOAN_PROCEEDS');
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click();
  checks.push('loan/owner funding remains a distinct income workspace classification');
  await workspace('Subscriber Growth');
  await page.getByRole('button', { name: /Opening active customers/ }).click();
  assert.equal(await page.getByRole('dialog').locator('tbody tr').count(), 1);
  await close();
  await page.getByRole('button', { name: /New line activations/ }).first().click();
  await page.getByRole('dialog').getByText('Activation', { exact: true }).first().waitFor();
  assert.equal(await page.getByRole('dialog').getByText('Migration baseline', { exact: true }).count(), 0);
  await close();
  await page.getByRole('button', { name: 'Bill-month settlement', exact: true }).click();
  await page.getByText('Loading reports and their supporting records…').waitFor({ state: 'hidden' });
  await page.locator('.finance-bar').filter({ hasText: 'Partially settled customers' }).click();
  await page.getByRole('dialog').getByText('₱130.00', { exact: true }).waitFor();
  await close(); checks.push('distinct customer/line drill-down, activation migration exclusion and partial bill-month settlement');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  const dialogs = await page.locator('[role="dialog"]').count(); assert.equal(dialogs, 0);
  if (process.env.FINANCE_UI_SCREENSHOT) await page.screenshot({ path: process.env.FINANCE_UI_SCREENSHOT, fullPage: true });
  checks.push('390px responsive page stays within viewport');
  readOnly = true; await mount();
  await workspace('Subscriber Growth');
  assert.equal(await page.getByRole('button', { name: 'Export CSV', exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Printable report', exact: true }).count(), 0);
  await workspace('Financial Reports');
  await page.getByText(/Your access does not include aggregate financial reports/).waitFor();
  checks.push('subscriber-only access excludes financial reports and output actions');
  assert.deepEqual(failures, []);
  assert.equal(requests.filter((r) => r.method !== 'GET').length, 1);
  console.log(JSON.stringify({ checks, browserErrors: failures, applicationWrites: 0, rejectedFixtureRequests: 1, origin: page.url() }, null, 2));
} catch (error) { console.error(JSON.stringify({ failures, text: (await page.locator('body').innerText()).slice(-3500), recentRequests: requests.slice(-8) }, null, 2)); throw error; } finally { await browser.close(); }
